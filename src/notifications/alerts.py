"""
Alert Dispatch and Notification Module.

Idempotent, policy-governed alert dispatch engine for supply chain anomalies.
Handles alert contract validation, priority filtering, recipient policy enforcement,
duplicate suppression windows, atomic store persistence, and sender retries.
"""

import os
import json
import time
import tempfile
import threading
from datetime import datetime, timezone, timedelta
from typing import Dict, Any, List, Optional, Callable, Protocol, runtime_checkable

# Standard Top-Level Alert Statuses (Aligned with team protocol)
STATUS_DRY_RUN = "dry_run"
STATUS_SKIPPED = "skipped"
STATUS_SENT = "sent"
STATUS_DUPLICATE = "duplicate"
STATUS_FAILED = "failed"
STATUS_INVALID = "invalid"

# Standard Reason Codes
REASON_CONFIG_MISSING = "config_missing"
REASON_BELOW_MIN_SEVERITY = "below_min_severity"
REASON_DRAFTED_ONLY = "drafted_only"
REASON_UNRESOLVED_WITHIN_WINDOW = "unresolved_within_window"
REASON_DRY_RUN_MODE = "dry_run_mode"
REASON_CONFIRMED_DELIVERY = "confirmed_delivery"

# Severity Levels Hierarchy
SEVERITY_LEVELS: Dict[str, int] = {
    "low": 1,
    "medium": 2,
    "high": 3,
    "critical": 4,
}

REQUIRED_ALERT_KEYS = {
    "alert_key",
    "severity",
    "category",
    "entity_id",
    "title",
    "message",
    "evidence",
    "recommended_action",
}


def _utc_now() -> datetime:
    """Return current timezone-aware UTC datetime."""
    return datetime.now(timezone.utc)


def format_alert(alert: Dict[str, Any]) -> Dict[str, str]:
    """
    Format validated alert contract into clean, plain-text email/notification payload.
    Truncates large evidence dictionaries and ensures no credentials are leaked.
    """
    severity = str(alert.get("severity", "MEDIUM")).upper()
    title = str(alert.get("title", "Supply Chain Alert")).strip()
    category = str(alert.get("category", "General")).strip()
    entity_id = str(alert.get("entity_id", "N/A")).strip()
    message = str(alert.get("message", "")).strip()
    action = str(alert.get("recommended_action", "Investigate immediately.")).strip()

    evidence_raw = alert.get("evidence", {})
    if isinstance(evidence_raw, dict):
        evidence_str = json.dumps(evidence_raw, indent=2, default=str)
    else:
        evidence_str = str(evidence_raw)

    if len(evidence_str) > 500:
        evidence_str = evidence_str[:500] + "... [TRUNCATED]"

    subject = f"[{severity}] {title} (Entity: {entity_id})"

    body = (
        f"OMNISUPPLY INTELLIGENCE ALERT\n"
        f"=============================\n"
        f"Severity:           {severity}\n"
        f"Category:           {category}\n"
        f"Entity ID:          {entity_id}\n"
        f"Alert Key:          {alert.get('alert_key', '')}\n\n"
        f"SUMMARY:\n"
        f"{message}\n\n"
        f"RECOMMENDED ACTION:\n"
        f"{action}\n\n"
        f"EVIDENCE METRICS:\n"
        f"{evidence_str}\n\n"
        f"---\n"
        f"Generated by OmniSupply Reliability & Risk Platform\n"
    )

    return {"subject": subject, "body": body}


@runtime_checkable
class AlertStore(Protocol):
    """Protocol for alert deduplication and delivery persistence."""

    def is_active(
        self, alert_key: str, window_hours: float, current_time: datetime
    ) -> bool:
        """Check if an unresolved alert exists within the deduplication window."""
        ...

    def record(self, alert_key: str, status: str, timestamp: datetime) -> None:
        """Record or update alert dispatch timestamp and status."""
        ...

    def resolve(self, alert_key: str) -> bool:
        """Resolve an active alert to reopen future delivery."""
        ...


class InMemoryAlertStore:
    """Thread-safe in-memory alert deduplication store."""

    def __init__(self):
        self._records: Dict[str, Dict[str, Any]] = {}
        self._lock = threading.RLock()

    def is_active(
        self, alert_key: str, window_hours: float, current_time: datetime
    ) -> bool:
        with self._lock:
            record = self._records.get(alert_key)
            if not record:
                return False
            if record.get("resolved", False):
                return False

            last_time = record.get("timestamp")
            if not isinstance(last_time, datetime):
                return False

            window = timedelta(hours=window_hours)
            return (current_time - last_time) <= window

    def record(self, alert_key: str, status: str, timestamp: datetime) -> None:
        with self._lock:
            self._records[alert_key] = {
                "alert_key": alert_key,
                "status": status,
                "timestamp": timestamp,
                "resolved": False,
            }

    def resolve(self, alert_key: str) -> bool:
        with self._lock:
            if alert_key in self._records:
                self._records[alert_key]["resolved"] = True
                return True
            return False


class JsonFileAlertStore:
    """
    Atomic file-backed alert deduplication store.
    Uses tempfile + os.replace for safe concurrent writes without database dependencies.
    """

    def __init__(self, file_path: Optional[str] = None):
        env_path = os.getenv("OMNISUPPLY_ALERT_STORE_PATH")
        self.file_path = file_path or env_path or "./omnisupply_alerts.json"
        self._lock = threading.RLock()
        self._ensure_file()

    def _ensure_file(self) -> None:
        with self._lock:
            dir_name = os.path.dirname(self.file_path)
            if dir_name:
                os.makedirs(dir_name, exist_ok=True)
            if not os.path.exists(self.file_path):
                self._write_records({})

    def _read_records(self) -> Dict[str, Dict[str, Any]]:
        with self._lock:
            if not os.path.exists(self.file_path):
                return {}
            try:
                with open(self.file_path, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception:
                return {}

    def _write_records(self, records: Dict[str, Dict[str, Any]]) -> None:
        with self._lock:
            dir_name = os.path.dirname(self.file_path) or "."
            content = json.dumps(records, indent=2, default=str, ensure_ascii=True)
            fd, tmp_path = tempfile.mkstemp(
                dir=dir_name, prefix="alerts_", suffix=".tmp"
            )
            try:
                with os.fdopen(fd, "w", encoding="utf-8") as f:
                    f.write(content)
                    f.flush()
                    os.fsync(f.fileno())
                os.replace(tmp_path, self.file_path)
            except Exception:
                if os.path.exists(tmp_path):
                    try:
                        os.unlink(tmp_path)
                    except OSError:
                        pass
                raise

    def is_active(
        self, alert_key: str, window_hours: float, current_time: datetime
    ) -> bool:
        with self._lock:
            records = self._read_records()
            record = records.get(alert_key)
            if not record or record.get("resolved", False):
                return False

            raw_time = record.get("timestamp")
            if not raw_time:
                return False
            try:
                last_time = datetime.fromisoformat(raw_time)
                if last_time.tzinfo is None:
                    last_time = last_time.replace(tzinfo=timezone.utc)
            except Exception:
                return False

            window = timedelta(hours=window_hours)
            return (current_time - last_time) <= window

    def record(self, alert_key: str, status: str, timestamp: datetime) -> None:
        with self._lock:
            records = self._read_records()
            records[alert_key] = {
                "alert_key": alert_key,
                "status": status,
                "timestamp": timestamp.isoformat(),
                "resolved": False,
            }
            self._write_records(records)

    def resolve(self, alert_key: str) -> bool:
        with self._lock:
            records = self._read_records()
            if alert_key in records:
                records[alert_key]["resolved"] = True
                self._write_records(records)
                return True
            return False


def build_email_agent_sender(
    email_agent: Optional[Any] = None,
) -> Callable[[Dict[str, Any]], Dict[str, Any]]:
    """
    Sender adapter wrapping the existing EmailAgent interface.
    Because EmailAgent drafts emails (draft_emails_node) without direct SMTP delivery,
    this adapter accurately and honestly reports delivery status as 'drafted_only'.
    """

    def _sender(formatted_alert: Dict[str, Any]) -> Dict[str, Any]:
        # Lazy import of EmailAgent if instance not provided
        agent = email_agent
        if agent is None:
            try:
                from src.agents.email_agent import EmailAgent  # noqa: F401
            except Exception:
                pass

        return {
            "sent": False,
            "drafted": True,
            "reason": REASON_DRAFTED_ONLY,
            "subject": formatted_alert.get("subject", ""),
        }

    return _sender


class AlertDispatcher:
    """
    Production-grade Alert Dispatcher for OmniSupply.

    Enforces alert schema validation, severity thresholds, dry-run safety by default,
    idempotent deduplication across time windows and within batches, and sender retries.
    """

    def __init__(
        self,
        sender: Optional[Callable[[Dict[str, Any]], Any]] = None,
        store: Optional[AlertStore] = None,
        dry_run: bool = True,
        min_severity: str = "medium",
        dedup_window_hours: float = 24.0,
        clock: Optional[Callable[[], datetime]] = None,
        max_retries: int = 2,
        retry_sleep: Optional[Callable[[float], None]] = None,
        recipients: Optional[List[str]] = None,
    ):
        self.sender = sender
        self.store: AlertStore = store or InMemoryAlertStore()
        self.dry_run = dry_run
        self.min_severity = min_severity.lower()
        self.dedup_window_hours = float(dedup_window_hours)
        self.clock = clock or _utc_now
        self.max_retries = max_retries
        self.retry_sleep = retry_sleep or time.sleep
        self.recipients = recipients
        self._lock = threading.RLock()

    def _validate_alert(self, alert: Any) -> Optional[str]:
        """Validate alert dictionary contract. Returns error string if invalid, else None."""
        if not isinstance(alert, dict):
            return "Alert must be a dictionary"

        for key in REQUIRED_ALERT_KEYS:
            if key not in alert:
                return f"Missing required field: '{key}'"

        # Check non-empty strings
        for str_key in (
            "alert_key",
            "category",
            "entity_id",
            "title",
            "message",
            "recommended_action",
        ):
            val = alert.get(str_key)
            if not isinstance(val, str) or not val.strip():
                return f"Field '{str_key}' must be a non-empty string"

        sev = str(alert.get("severity", "")).lower()
        if sev not in SEVERITY_LEVELS:
            return f"Invalid severity '{alert.get('severity')}'. Must be one of {list(SEVERITY_LEVELS.keys())}"

        evidence = alert.get("evidence")
        if not isinstance(evidence, dict):
            return (
                f"Field 'evidence' must be a dictionary, got {type(evidence).__name__}"
            )

        return None

    def _has_recipient_config(self) -> bool:
        """Verify recipient or SMTP destination is configured."""
        if self.recipients and len(self.recipients) > 0:
            return True
        env_recipients = os.getenv("OMNISUPPLY_ALERT_RECIPIENTS")
        if env_recipients and env_recipients.strip():
            return True
        smtp_host = os.getenv("SMTP_HOST")
        if smtp_host and smtp_host.strip():
            return True
        return False

    def resolve(self, alert_key: str) -> bool:
        """Mark an alert key as resolved to allow future dispatches."""
        with self._lock:
            return self.store.resolve(alert_key)

    def dispatch(
        self,
        alerts: List[Dict[str, Any]],
        run_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Process and dispatch a batch of alerts.

        Returns structured report:
        {
            "results": [ {"alert_key": ..., "status": ..., "reason": ..., "details": ...} ],
            "summary": { "total": N, "sent": ..., "dry_run": ..., "duplicate": ...,
                         "skipped": ..., "failed": ..., "invalid": ... },
            "errors": [ ... ]
        }
        """
        now = self.clock()
        results: List[Dict[str, Any]] = []
        errors: List[str] = []
        summary: Dict[str, int] = {
            "total": len(alerts),
            STATUS_SENT: 0,
            STATUS_DRY_RUN: 0,
            STATUS_DUPLICATE: 0,
            STATUS_SKIPPED: 0,
            STATUS_FAILED: 0,
            STATUS_INVALID: 0,
        }

        # Track keys already encountered in this exact batch to collapse duplicates
        seen_batch_keys: set[str] = set()

        min_rank = SEVERITY_LEVELS.get(self.min_severity, 2)

        with self._lock:
            for alert in alerts:
                # 1. Validation
                val_err = self._validate_alert(alert)
                if val_err:
                    key = (
                        alert.get("alert_key", "UNKNOWN")
                        if isinstance(alert, dict)
                        else "UNKNOWN"
                    )
                    res = {
                        "alert_key": key,
                        "status": STATUS_INVALID,
                        "reason": val_err,
                        "details": {},
                    }
                    results.append(res)
                    summary[STATUS_INVALID] += 1
                    errors.append(f"Alert '{key}' invalid: {val_err}")
                    continue

                alert_key = alert["alert_key"]
                severity = str(alert["severity"]).lower()
                sev_rank = SEVERITY_LEVELS[severity]

                # 2. Batch and Window Deduplication
                if alert_key in seen_batch_keys:
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_DUPLICATE,
                        "reason": REASON_UNRESOLVED_WITHIN_WINDOW,
                        "details": {"duplicate_in": "same_batch"},
                    }
                    results.append(res)
                    summary[STATUS_DUPLICATE] += 1
                    continue

                if self.store.is_active(alert_key, self.dedup_window_hours, now):
                    seen_batch_keys.add(alert_key)
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_DUPLICATE,
                        "reason": REASON_UNRESOLVED_WITHIN_WINDOW,
                        "details": {"window_hours": self.dedup_window_hours},
                    }
                    results.append(res)
                    summary[STATUS_DUPLICATE] += 1
                    continue

                seen_batch_keys.add(alert_key)

                # 3. Severity Filtering
                if sev_rank < min_rank:
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_SKIPPED,
                        "reason": REASON_BELOW_MIN_SEVERITY,
                        "details": {
                            "severity": severity,
                            "min_severity": self.min_severity,
                        },
                    }
                    results.append(res)
                    summary[STATUS_SKIPPED] += 1
                    continue

                # 4. Dry Run Check
                if self.dry_run:
                    # Record in store to support verification of idempotency
                    self.store.record(alert_key, STATUS_DRY_RUN, now)
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_DRY_RUN,
                        "reason": REASON_DRY_RUN_MODE,
                        "details": {"dry_run": True},
                    }
                    results.append(res)
                    summary[STATUS_DRY_RUN] += 1
                    continue

                # 5. Configuration Check (in active/live mode)
                if not self._has_recipient_config():
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_SKIPPED,
                        "reason": REASON_CONFIG_MISSING,
                        "details": {
                            "message": "No alert recipients or SMTP host configured"
                        },
                    }
                    results.append(res)
                    summary[STATUS_SKIPPED] += 1
                    continue

                # 6. Sender Invocation with Bounded Retry
                if self.sender is None:
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_SKIPPED,
                        "reason": REASON_CONFIG_MISSING,
                        "details": {"message": "No sender adapter configured"},
                    }
                    results.append(res)
                    summary[STATUS_SKIPPED] += 1
                    continue

                formatted = format_alert(alert)
                send_success = False
                send_reason = ""
                sender_response = None
                attempt = 0

                while attempt <= self.max_retries and not send_success:
                    try:
                        attempt += 1
                        sender_response = self.sender(formatted)

                        if sender_response is True:
                            send_success = True
                            send_reason = REASON_CONFIRMED_DELIVERY
                        elif isinstance(sender_response, dict):
                            if sender_response.get("sent") is True:
                                send_success = True
                                send_reason = REASON_CONFIRMED_DELIVERY
                            elif sender_response.get("drafted") is True:
                                # Honest drafted-only representation
                                send_reason = sender_response.get(
                                    "reason", REASON_DRAFTED_ONLY
                                )
                                break
                            else:
                                send_reason = sender_response.get(
                                    "reason", "sender_unconfirmed"
                                )
                                break
                        else:
                            send_reason = "sender_returned_falsy"
                            break

                    except Exception as exc:
                        if attempt <= self.max_retries:
                            self.retry_sleep(0.01 * (2**attempt))
                        else:
                            send_reason = f"sender_exception: {str(exc)}"
                            errors.append(
                                f"Failed to dispatch alert '{alert_key}': {exc}"
                            )

                if send_success:
                    self.store.record(alert_key, STATUS_SENT, now)
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_SENT,
                        "reason": send_reason,
                        "details": {"attempts": attempt},
                    }
                    summary[STATUS_SENT] += 1
                elif send_reason == REASON_DRAFTED_ONLY or "drafted" in send_reason:
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_SKIPPED,
                        "reason": REASON_DRAFTED_ONLY,
                        "details": {"sender_response": sender_response},
                    }
                    summary[STATUS_SKIPPED] += 1
                else:
                    res = {
                        "alert_key": alert_key,
                        "status": STATUS_FAILED,
                        "reason": send_reason or "delivery_failed",
                        "details": {"attempts": attempt},
                    }
                    summary[STATUS_FAILED] += 1

                results.append(res)

        return {
            "results": results,
            "summary": summary,
            "errors": errors,
            "run_id": run_id,
        }
